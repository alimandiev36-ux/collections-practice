# Файл: collections.py
# Вариант 6. Словарь оценок по предметам.
# Демонстрация работы со списками, словарями и множествами.

# ============================================================
# 1. ИСХОДНЫЕ ДАННЫЕ
# ============================================================
grades = {
    "Математика": 5,
    "Физика": 4,
    "Химия": 3,
    "История": 5,
    "Информатика": 4,
    "Литература": 3,
    "Английский": 5,
}

subjects = list(grades.keys())

print("=" * 60)
print("ИСХОДНЫЕ ДАННЫЕ")
print("=" * 60)
print("\nИсходный словарь оценок по предметам:")
for subject, grade in grades.items():
    print(f"  {subject}: {grade}")

print("\nИсходный список предметов:")
print(subjects)


# ============================================================
# 2. ОПЕРАЦИИ СО СПИСКОМ
# ============================================================
print("\n" + "=" * 60)
print("ОПЕРАЦИИ СО СПИСКОМ")
print("=" * 60)

# Обращение по индексу
print("\nПервый предмет (индекс 0):", subjects[0])
print("Последний предмет (индекс -1):", subjects[-1])

# Срезы
print("\nСрез первых трёх предметов:", subjects[:3])
print("Срез с шагом 2:", subjects[::2])

# Добавление
subjects.append("География")
grades["География"] = 4
print("\nПосле добавления 'География':", subjects)

# Изменение (меняем оценку по Химии в словаре — данные остаются чистыми)
grades["Химия"] = 4
print("Оценка по 'Химия' после изменения:", grades["Химия"])

# Удаление последнего элемента списка
removed = subjects.pop()
removed_grade = grades.pop(removed)
print(f"\nУдалён предмет: {removed} (оценка {removed_grade})")
print("После удаления:", subjects)

# Обход коллекции в цикле
print("\nОбход списка в цикле:")
for i, subject in enumerate(subjects, start=1):
    print(f"  {i}. {subject}")


# ============================================================
# 3. РАБОТА СО СЛОВАРЁМ
# ============================================================
print("\n" + "=" * 60)
print("РАБОТА СО СЛОВАРЁМ")
print("=" * 60)

# Добавление
grades["Обществознание"] = 4

# Доступ по ключу
print("\nОценка по 'Математика':", grades["Математика"])
print("Оценка по 'Астрономия' (get):", grades.get("Астрономия", "нет данных"))

# Изменение значения
grades["Литература"] = 4
print("Оценка по 'Литература' после изменения:", grades["Литература"])

# Ключи и значения
print("\nКлючи словаря (предметы):")
for key in grades.keys():
    print("  ", key)

print("\nЗначения словаря (оценки):")
for value in grades.values():
    print("  ", value)


# ============================================================
# 4. СРЕДНИЙ БАЛЛ
# ============================================================
print("\n" + "=" * 60)
print("СРЕДНИЙ БАЛЛ")
print("=" * 60)

total = sum(grades.values())
average = total / len(grades)
print(f"\nСумма баллов: {total}")
print(f"Количество предметов: {len(grades)}")
print(f"Средний балл: {average:.2f}")


# ============================================================
# 5. РАБОТА С МНОЖЕСТВАМИ
# ============================================================
print("\n" + "=" * 60)
print("РАБОТА С МНОЖЕСТВАМИ")
print("=" * 60)

# Уникальные оценки (дубликаты удаляются автоматически)
unique_grades = set(grades.values())
print("\nМножество уникальных оценок:", unique_grades)

# Проверка вхождения
print("Есть ли оценка 5 в множестве:", 5 in unique_grades)
print("Есть ли оценка 2 в множестве:", 2 in unique_grades)

# Множества предметов
excellent_only = {s for s, g in grades.items() if g == 5}
high_achievers = {s for s, g in grades.items() if g >= 4}
print("\nОтличники (оценка 5):", excellent_only)
print("Хорошисты и отличники (4 и 5):", high_achievers)

# Операции над множествами
print("\nПересечение (отличники ∩ хорошисты):", excellent_only & high_achievers)
print("Разность (хорошисты - отличники):", high_achievers - excellent_only)
print("Объединение (все успевающие):", high_achievers | excellent_only)


# ============================================================
# 6. ФИЛЬТРАЦИЯ: ОЦЕНКИ 4 И ВЫШЕ
# ============================================================
print("\n" + "=" * 60)
print("ФИЛЬТРАЦИЯ: ОЦЕНКИ 4 И ВЫШЕ")
print("=" * 60)

good_subjects = {s: g for s, g in grades.items() if g >= 4}
print("\nПредметы с оценкой 4 и выше:")
for subject, g in good_subjects.items():
    print(f"  {subject}: {g}")

good_subjects_list = [s for s, g in grades.items() if g >= 4]
print("\nСписок предметов с оценкой 4 и выше:", good_subjects_list)
print("Количество таких предметов:", len(good_subjects_list))


# ============================================================
# 7. ПРЕОБРАЗОВАНИЕ ДАННЫХ
# ============================================================
print("\n" + "=" * 60)
print("ПРЕОБРАЗОВАНИЕ ДАННЫХ")
print("=" * 60)

grade_text = {
    5: "отлично",
    4: "хорошо",
    3: "удовлетворительно",
    2: "неудовлетворительно",
}

formatted = [f"{s}: {g} ({grade_text.get(g, '—')})" for s, g in grades.items()]
print("\nОценки в текстовом виде:")
for line in formatted:
    print("  ", line)

print("\nСтроки вида 'Предмет — оценка — текст':")
for s, g in grades.items():
    print(f"  {s} — {g} — {grade_text.get(g, '—')}")


# ============================================================
# 8. СОРТИРОВКА
# ============================================================
print("\n" + "=" * 60)
print("СОРТИРОВКА")
print("=" * 60)

by_name = sorted(grades.items(), key=lambda item: item[0])
print("\nПо названию предмета:")
for s, g in by_name:
    print(f"  {s}: {g}")

by_grade_desc = sorted(grades.items(), key=lambda item: item[1], reverse=True)
print("\nПо оценке (по убыванию):")
for s, g in by_grade_desc:
    print(f"  {s}: {g}")


# ============================================================
# 9. ИТОГОВАЯ СВОДКА
# ============================================================
print("\n" + "=" * 60)
print("ИТОГОВАЯ СВОДКА")
print("=" * 60)
print(f"Всего предметов: {len(grades)}")
print(f"Средний балл: {average:.2f}")
print(f"Уникальные оценки: {sorted(unique_grades)}")
print(f"Предметов с оценкой 4+: {len(good_subjects_list)}")
print(f"Отличных оценок (5): {sum(1 for g in grades.values() if g == 5)}")